-- Return opportunities only. No worker, provider calls or historical backfill.
ALTER TABLE agendamentos ADD COLUMN completed_at TIMESTAMPTZ;
ALTER TABLE agendamentos ADD CONSTRAINT return_appointment_owner UNIQUE (assinatura_id, id);

CREATE FUNCTION studiofy_return_phone(value TEXT) RETURNS TEXT
LANGUAGE sql IMMUTABLE AS $$
 SELECT CASE
  WHEN value IS NULL OR value !~ '^[+0-9 ()-]+$' THEN NULL
  WHEN regexp_replace(value, '[^0-9]', '', 'g') ~ '^[1-9][1-9]([2-5][0-9]{7}|9[0-9]{8})$'
   THEN '55' || regexp_replace(value, '[^0-9]', '', 'g')
  WHEN regexp_replace(value, '[^0-9]', '', 'g') ~ '^55[1-9][1-9]([2-5][0-9]{7}|9[0-9]{8})$'
   THEN regexp_replace(value, '[^0-9]', '', 'g')
  ELSE NULL END
$$;

CREATE FUNCTION studiofy_return_customer_key(tenant BIGINT, phone TEXT) RETURNS TEXT
LANGUAGE plpgsql VOLATILE AS $$
DECLARE secret TEXT;
BEGIN
 SELECT valor INTO secret FROM configuracoes WHERE chave='return_customer_key_v1';
 IF NOT FOUND THEN
  -- Initialize atomically on the first valid completion, preserving empty import targets.
  -- Never replace an existing secret, even if it is invalid.
  INSERT INTO configuracoes(chave,valor)
   VALUES ('return_customer_key_v1',replace(gen_random_uuid()::text,'-','') || replace(gen_random_uuid()::text,'-',''))
   ON CONFLICT(chave) DO UPDATE SET valor=configuracoes.valor RETURNING valor INTO secret;
 END IF;
 IF secret IS NULL OR secret !~ '^[a-f0-9]{64}$' THEN
  RAISE EXCEPTION 'Return identity configuration unavailable' USING ERRCODE='23514';
 END IF;
 -- Fixed domain, validated phone and tenant; secret suffix avoids prefix-hash extension.
 RETURN encode(sha256(convert_to('return-customer:v1:' || tenant::text || ':' || phone || ':' || secret, 'UTF8')), 'hex');
END $$;

CREATE TABLE return_reminders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 assinatura_id BIGINT NOT NULL REFERENCES assinaturas(id) ON DELETE CASCADE,
 appointment_id BIGINT NOT NULL,
 service_identity TEXT NOT NULL CHECK (service_identity ~ '^service:[1-9][0-9]*$'),
 customer_key TEXT NOT NULL CHECK (customer_key ~ '^[a-f0-9]{64}$'),
 customer_name_snapshot TEXT NOT NULL CHECK (length(btrim(customer_name_snapshot)) BETWEEN 2 AND 100),
 phone_snapshot TEXT NOT NULL CHECK (phone_snapshot ~ '^55[1-9][1-9]([2-5][0-9]{7}|9[0-9]{8})$'),
 service_name_snapshot TEXT NOT NULL CHECK (length(btrim(service_name_snapshot)) BETWEEN 1 AND 100),
 completed_at TIMESTAMPTZ NOT NULL,
 eligible_at TIMESTAMPTZ NOT NULL,
 status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','processing','sent','suppressed','cancelled','failed','uncertain')),
 reason_code TEXT CHECK (reason_code IN ('newer_completion','invalid_recipient','unavailable_service','account_unavailable','cancelled','provider_rejected','delivery_uncertain')),
 attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
 next_attempt_at TIMESTAMPTZ NOT NULL,
 claim_token UUID, claimed_at TIMESTAMPTZ, lease_until TIMESTAMPTZ,
 dispatch_started_at TIMESTAMPTZ, provider_message_id TEXT, sent_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 UNIQUE (assinatura_id, appointment_id),
 FOREIGN KEY (assinatura_id, appointment_id) REFERENCES agendamentos(assinatura_id, id) ON DELETE CASCADE,
 CHECK (eligible_at = ((completed_at AT TIME ZONE 'America/Sao_Paulo') + interval '7 days') AT TIME ZONE 'America/Sao_Paulo')
);
CREATE INDEX return_reminder_pending ON return_reminders(next_attempt_at, id) WHERE status='pending';
CREATE INDEX return_reminder_reference ON return_reminders(assinatura_id, customer_key, service_identity, completed_at DESC, id DESC);

CREATE FUNCTION studiofy_return_completion_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE moment TIMESTAMPTZ;
BEGIN
 IF TG_OP='INSERT' THEN
  IF NEW.completed_at IS NOT NULL THEN
   RAISE EXCEPTION 'Completion timestamp is server controlled' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
 END IF;
 -- Ownership is fixed at creation, including NULL legacy owners. Validate OLD facts.
 IF OLD.assinatura_id IS DISTINCT FROM NEW.assinatura_id THEN
  RAISE EXCEPTION 'Appointment owner is immutable' USING ERRCODE='23514';
 END IF;
 IF NEW.status='concluido' AND OLD.status='confirmado' THEN
  moment := clock_timestamp();
  IF NEW.data IS NULL OR NEW.hora IS NULL OR NEW.data !~ '^\d{4}-\d{2}-\d{2}$'
    OR NEW.hora !~ '^([01]\d|2[0-3]):[0-5]\d$'
    OR ((NEW.data || ' ' || NEW.hora)::timestamp AT TIME ZONE 'America/Sao_Paulo') > moment THEN
   RAISE EXCEPTION 'Future or invalid appointment cannot be completed' USING ERRCODE='23514';
  END IF;
  NEW.completed_at := moment;
 ELSIF NEW.completed_at IS DISTINCT FROM OLD.completed_at THEN
  RAISE EXCEPTION 'Completion timestamp is immutable' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER studiofy_return_completion_guard BEFORE INSERT OR UPDATE ON agendamentos
FOR EACH ROW EXECUTE FUNCTION studiofy_return_completion_guard();

CREATE FUNCTION studiofy_return_opportunity_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE source agendamentos%ROWTYPE; phone TEXT;
BEGIN
 SELECT * INTO source FROM agendamentos WHERE id=NEW.appointment_id AND assinatura_id=NEW.assinatura_id;
 phone := studiofy_return_phone(source.telefone);
 IF source.id IS NULL OR source.status<>'concluido' OR source.completed_at IS NULL
   OR source.studio_service_id IS NULL OR phone IS NULL
   OR NEW.completed_at IS DISTINCT FROM source.completed_at
   OR NEW.service_identity IS DISTINCT FROM ('service:' || source.studio_service_id::text)
   OR NEW.customer_key IS DISTINCT FROM studiofy_return_customer_key(source.assinatura_id,phone)
   OR NEW.customer_name_snapshot IS DISTINCT FROM source.nome_cliente
   OR NEW.phone_snapshot IS DISTINCT FROM phone
   OR NEW.service_name_snapshot IS DISTINCT FROM source.servico_nome THEN
  RAISE EXCEPTION 'Return opportunity does not match completed appointment' USING ERRCODE='23514';
 END IF;
 IF TG_OP='INSERT' AND (NEW.status<>'pending' OR NEW.attempts<>0 OR NEW.dispatch_started_at IS NOT NULL
   OR NEW.sent_at IS NOT NULL OR NEW.provider_message_id IS NOT NULL) THEN
  RAISE EXCEPTION 'Return opportunity must start pending' USING ERRCODE='23514';
 END IF;
 IF TG_OP='UPDATE' AND ROW(NEW.assinatura_id,NEW.appointment_id,NEW.service_identity,NEW.customer_key,
   NEW.customer_name_snapshot,NEW.phone_snapshot,NEW.service_name_snapshot,NEW.completed_at,NEW.eligible_at)
   IS DISTINCT FROM ROW(OLD.assinatura_id,OLD.appointment_id,OLD.service_identity,OLD.customer_key,
   OLD.customer_name_snapshot,OLD.phone_snapshot,OLD.service_name_snapshot,OLD.completed_at,OLD.eligible_at) THEN
  RAISE EXCEPTION 'Return opportunity facts are immutable' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER studiofy_return_opportunity_guard BEFORE INSERT OR UPDATE ON return_reminders
FOR EACH ROW EXECUTE FUNCTION studiofy_return_opportunity_guard();

CREATE FUNCTION studiofy_return_opportunity_create() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE phone TEXT; due TIMESTAMPTZ;
BEGIN
 -- Legacy/missing catalog references and invalid contacts do not authorize a message.
 phone := studiofy_return_phone(NEW.telefone);
 IF NEW.assinatura_id IS NULL OR NEW.studio_service_id IS NULL OR phone IS NULL
   OR NEW.nome_cliente IS NULL OR length(btrim(NEW.nome_cliente)) NOT BETWEEN 2 AND 100
   OR NEW.servico_nome IS NULL OR length(btrim(NEW.servico_nome)) NOT BETWEEN 1 AND 100
   OR NOT EXISTS (SELECT 1 FROM servicos_assinatura WHERE id=NEW.studio_service_id AND assinatura_id=NEW.assinatura_id) THEN
  RETURN NEW;
 END IF;
 due := ((NEW.completed_at AT TIME ZONE 'America/Sao_Paulo') + interval '7 days') AT TIME ZONE 'America/Sao_Paulo';
 INSERT INTO return_reminders(assinatura_id,appointment_id,service_identity,customer_key,
   customer_name_snapshot,phone_snapshot,service_name_snapshot,completed_at,eligible_at,next_attempt_at)
 VALUES (NEW.assinatura_id,NEW.id,'service:' || NEW.studio_service_id::text,
   studiofy_return_customer_key(NEW.assinatura_id,phone),NEW.nome_cliente,phone,NEW.servico_nome,NEW.completed_at,due,due)
 ON CONFLICT (assinatura_id,appointment_id) DO NOTHING;
 RETURN NEW;
END $$;
CREATE TRIGGER studiofy_return_opportunity_create AFTER UPDATE ON agendamentos
FOR EACH ROW WHEN (OLD.status='confirmado' AND NEW.status='concluido')
EXECUTE FUNCTION studiofy_return_opportunity_create();
